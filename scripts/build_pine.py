"""Assemble standalone Pine files from one engine and one publication layer."""
from pathlib import Path
import hashlib

ROOT = Path(__file__).resolve().parents[1]
engine = (ROOT / "pine/engine.pinepart").read_text()
view = (ROOT / "pine/view.pinepart").read_text()
VERSION = "1.6.6"
header = f"//@version=6\n// Trend Line v{VERSION} — MIT License. Copyright 2026 Matthias Mandiau and Three Towers contributors.\n"
header += "// Generated by scripts/build_pine.py; full source and methodology accompany this file.\n"
header += f"// Engine SHA256: {hashlib.sha256(engine.encode()).hexdigest()}\n"
indicator = 'indicator("Trend Line", shorttitle = "Trend Line", overlay = true, max_labels_count = 500, max_lines_count = 200, max_polylines_count = 100)\n'
strategy = 'strategy("Trend Line — Backtest", shorttitle = "Trend BT", overlay = true, max_labels_count = 500, max_lines_count = 200, max_polylines_count = 100, initial_capital = 10000, default_qty_type = strategy.percent_of_equity, default_qty_value = 99, pyramiding = 0, commission_type = strategy.commission.percent, commission_value = 0.3, slippage = 0, margin_long = 100, calc_on_every_tick = false, calc_on_order_fills = false, process_orders_on_close = false)\n'
orders = '''
// TradingView's slippage property is TICKS, not percent. Percentage scenarios live
// in the reference backtest. This strategy uses 0.3% commission and 0 ticks by default.
int testStart = input.time(timestamp("1970-01-01T00:00:00+00:00"), "First signal date", group = "Backtest")
int testEnd = input.time(timestamp("2099-01-01T00:00:00+00:00"), "Last signal date (exclusive)", group = "Backtest")
if barstate.isfirst and not nativeTf
    runtime.error("Run the baseline backtest on standard 1W candles. Other intervals are indicator viewing surfaces.")
if testEnd <= testStart
    runtime.error("Last signal date must follow first signal date.")
bool inRange = time_close >= testStart and time_close < testEnd
bool enterExisting = input.bool(false, "Enter existing bull at start", group = "Backtest")
var bool started = false
if barstate.isconfirmed and inRange and assetReady and (bull or (enterExisting and not started and asset.regime == 1))
    strategy.entry("Trend long", strategy.long)
if barstate.isconfirmed and inRange and assetReady
    started := true
if barstate.isconfirmed and bear and strategy.position_size > 0
    strategy.close("Trend long", comment = "Bearish confirmation")
if barstate.isconfirmed and time_close >= testEnd and strategy.position_size > 0
    strategy.close("Trend long", comment = "End of test window")
'''
# Put routine model/display controls before advanced engine inputs in Settings.
# The engine bytes and declaration order within each block stay unchanged.
view_inputs, view_runtime = view.split("bool weekly =", 1)
shared = f'string PLUGIN_VERSION = "{VERSION}"\n' + view_inputs + "\n" + engine + "\n" + (ROOT / "pine/ledger.pinepart").read_text() + "\n" + (ROOT / "pine/context.pinepart").read_text() + "\n" + "bool weekly =" + view_runtime
build_id = hashlib.sha256(shared.encode()).hexdigest()[:12]
shared = f'string BUILD_ID = "{build_id}"\n' + shared
(ROOT / "trend_line.pine").write_text(header + indicator + "\nconst bool IS_BACKTEST = false\n" + shared)
(ROOT / "trend_line_backtest.pine").write_text(header + strategy + "\nconst bool IS_BACKTEST = true\n" + shared + orders)
print(f"Built both Pine v6 scripts from the shared engine. Build {build_id}.")
